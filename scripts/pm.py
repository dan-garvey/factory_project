#!/usr/bin/env python3
"""Local hourly wakeups for the explicit progenitor thread; not a review engine.

Runtime state and locks live in the common Git directory, never in source or the
Beads database. A queue receipt proves delivery admission, not a completed review.
"""

import argparse
from datetime import datetime, timezone
import fcntl
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import uuid


ROOT = Path(__file__).resolve().parents[1]
UNIT_MARKER = "# Factory PM managed unit; generated by scripts/pm.py\n"


def now():
    return datetime.now(timezone.utc).isoformat()


def read_json(path):
    return json.loads(path.read_text()) if path.exists() else {}


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        json.dump(value, stream, indent=2)
        stream.write("\n")
    temporary.replace(path)


def quote_unit(value, command=False):
    text = str(value).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    if command:
        text = text.replace("$", "$$")
    if "\n" in text or "\r" in text:
        raise ValueError("Unit paths cannot contain newlines")
    return '"' + text + '"'


def working_directory(value):
    text = str(value)
    if "\n" in text or "\r" in text:
        raise ValueError("Unit paths cannot contain newlines")
    # WorkingDirectory preserves quotes; unlike ExecStart it needs a raw path.
    return text.replace("%", "%%")


def install(root, directory, thread, codex, unit_directory):
    uuid.UUID(thread)
    # Keep the stable launcher path; resolving current/version symlinks would
    # pin the timer to an obsolete package after an automatic CLI update.
    codex = Path(codex).absolute()
    if not codex.is_file():
        raise ValueError(f"Codex launcher does not exist: {codex}")
    service = UNIT_MARKER + f"""[Unit]
Description=Queue an hourly review to the Factory progenitor

[Service]
Type=oneshot
WorkingDirectory={working_directory(root)}
ExecStart={quote_unit(sys.executable, command=True)} -B {quote_unit(root / 'scripts/pm.py', command=True)} poll
TimeoutStartSec=60
# Codex owns its daemon lifecycle. Do not kill a daemon the queue CLI may start.
KillMode=process
Nice=10
IOSchedulingClass=idle
"""
    timer = UNIT_MARKER + """[Unit]
Description=Hourly Factory project-management review

[Timer]
OnCalendar=hourly
Persistent=true
RandomizedDelaySec=120
Unit=factory-pm.service

[Install]
WantedBy=timers.target
"""
    units = {"factory-pm.service": service, "factory-pm.timer": timer}
    # No unrelated unit may be overwritten; changed owned units also need review.
    for name, content in units.items():
        path = unit_directory / name
        if path.is_symlink():
            raise ValueError(f"Refusing an existing unit symlink: {path}")
        if path.exists() and path.read_text() != content:
            raise ValueError(f"Refusing to overwrite a different unit: {path}")
    config = {"thread": thread, "codex": str(codex), "root": str(root)}
    previous = read_json(directory / "pm-config.json")
    if previous and previous != config:
        raise ValueError("Existing PM configuration differs; reconcile it explicitly")
    unit_directory.mkdir(parents=True, exist_ok=True)
    for name, content in units.items():
        (unit_directory / name).write_text(content)
    write_json(directory / "pm-config.json", config)


class Manager:
    def __init__(self, root, directory):
        self.root = root
        self.directory = directory
        self.state_path = directory / "pm-state.json"

    def snapshot(self):
        refs = subprocess.check_output(
            ["git", "-C", str(self.root), "for-each-ref", "--format=%(refname) %(objectname)", "refs/heads"],
            text=True,
        )
        return {"refs": refs.splitlines(), "free_disk_bytes": shutil.disk_usage(self.root).free}

    def poll(self, dry_run=False, queue=subprocess.run):
        config = read_json(self.directory / "pm-config.json")
        if not config or config["root"] != str(self.root):
            raise ValueError("Install PM configuration for this main checkout first")
        state = read_json(self.state_path)
        snapshot = self.snapshot()
        if dry_run:
            return {"dry_run": True, "target_thread": config["thread"], **snapshot, "pending": state.get("pending")}
        state["last_poll"] = {"at": now(), **snapshot}
        if state.get("pending"):
            write_json(self.state_path, state)
            return {"coalesced": True, "pending": state["pending"]}
        request = {"id": str(uuid.uuid4()), "at": now(), "refs": snapshot["refs"], "status": "submitting"}
        state["pending"] = request
        write_json(self.state_path, state)
        prompt = (
            f"Hourly Factory PM review, request {request['id']}. This continues the existing PM assignment; "
            f"it does not replace unfinished user work. In {self.root}, read PROJECT_MANAGER.md and inspect "
            "new commits on main and work branches against DESIGN.md, task scope and evidence; coordinate owners "
            "and local resources. Do not approve open gameplay choices or implement unrequested fixes. "
            "Record exact reviewed revisions, findings and limits in Beads, then acknowledge this request using "
            f"python3 -B scripts/pm.py acknowledge --request {request['id']} --summary 'review ledger reference'."
        )
        try:
            receipt = queue([config["codex"], "queue", "--thread", config["thread"], "--message", prompt],
                            text=True, capture_output=True, check=True, timeout=30)
        except subprocess.TimeoutExpired:
            request["status"] = "delivery_unknown"
            state["last_error"] = "Queue timeout: inspect the thread before clearing/retrying the pending request"
            write_json(self.state_path, state)
            raise
        except subprocess.CalledProcessError as error:
            request["status"] = "delivery_unknown"
            state["last_error"] = {
                "message": f"Queue exited after launch; inspect thread before retrying: {error}",
                "stderr": (error.stderr or "")[-2000:],
                "stdout": (error.stdout or "")[-1000:],
            }
            write_json(self.state_path, state)
            raise
        except OSError as error:
            state["pending"] = None
            state["last_error"] = str(error)
            write_json(self.state_path, state)
            raise
        request["status"] = "queued"
        request["receipt"] = receipt.stdout.strip()[:500]
        state.pop("last_error", None)
        write_json(self.state_path, state)
        return {"queued": request}

    def acknowledge(self, request_id, summary):
        state = read_json(self.state_path)
        pending = state.get("pending")
        if not pending or pending["id"] != request_id:
            raise ValueError("Request does not match the pending review; nothing acknowledged")
        state["last_completed"] = {**pending, "completed_at": now(), "summary": summary}
        state["pending"] = None
        state.pop("last_error", None)
        write_json(self.state_path, state)
        return state["last_completed"]

    def cancel(self, request_id, reason):
        state = read_json(self.state_path)
        pending = state.get("pending")
        if not pending or pending["id"] != request_id:
            raise ValueError("Request does not match; nothing cancelled")
        state["last_cancelled"] = {**pending, "cancelled_at": now(), "reason": reason}
        state["pending"] = None
        write_json(self.state_path, state)
        return state["last_cancelled"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    setup = commands.add_parser("install", help="generate local config/units, without starting services")
    setup.add_argument("--thread", required=True)
    setup.add_argument("--codex", default=shutil.which("codex"))
    poll = commands.add_parser("poll", help="queue once; coalesce until acknowledged")
    poll.add_argument("--dry-run", action="store_true")
    commands.add_parser("status")
    ack = commands.add_parser("acknowledge")
    ack.add_argument("--request", required=True)
    ack.add_argument("--summary", required=True)
    cancel = commands.add_parser("cancel", help="clear an inspected stale request, without claiming a review")
    cancel.add_argument("--request", required=True)
    cancel.add_argument("--reason", required=True)
    args = parser.parse_args()
    try:
        common = Path(subprocess.check_output(
            ["git", "-C", str(ROOT), "rev-parse", "--path-format=absolute", "--git-common-dir"], text=True).strip()).resolve()
        if common.name != ".git" or ROOT != common.parent:
            raise ValueError("Operate PM from the main checkout, not a linked worktree")
        directory = common / "factory-ops"
        directory.mkdir(exist_ok=True)
        with (directory / "pm.lock").open("a") as lock:
            fcntl.flock(lock, fcntl.LOCK_EX)
            manager = Manager(ROOT, directory)
            if args.command == "install":
                install(ROOT, directory, args.thread, args.codex, Path.home() / ".config/systemd/user")
                result = {"installed": True, "enabled": False, "thread": args.thread}
            elif args.command == "poll":
                result = manager.poll(args.dry_run)
            elif args.command == "acknowledge":
                result = manager.acknowledge(args.request, args.summary)
            elif args.command == "cancel":
                result = manager.cancel(args.request, args.reason)
            else:
                result = {"config": read_json(directory / "pm-config.json"), "state": read_json(manager.state_path)}
        print(json.dumps(result, indent=2))
        return 0
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(f"PM ERROR: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
